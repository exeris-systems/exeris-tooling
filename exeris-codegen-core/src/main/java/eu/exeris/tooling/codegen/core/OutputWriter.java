package eu.exeris.tooling.codegen.core;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Objects;
import java.util.Set;
import java.util.TreeSet;

/**
 * Utility for writing generated code to files.
 * <p>
 * Handles:
 * <ul>
 *   <li>Directory creation</li>
 *   <li>Package-to-path conversion</li>
 *   <li>File headers with generation metadata</li>
 *   <li>Output-tree ownership: tracks every file it writes and, on
 *       {@link #pruneOrphansAndWriteManifest()}, deletes files emitted by a
 *       previous run that this run no longer produces</li>
 * </ul>
 *
 * <h2>Generation owns its output tree</h2>
 * Each run records the relative path of every file it writes. A manifest
 * ({@value #MANIFEST_NAME}) under the output directory persists that set across
 * runs. On the next run, any path that was in the previous manifest but is not
 * re-emitted is an <em>orphan</em> (the entity was removed or re-homed) and is
 * deleted, then now-empty directories are pruned. Only files this tool emitted
 * before are ever deleted — a user-authored file never appears in the manifest,
 * so it is never touched. The manifest is sorted, so its content is
 * deterministic for the same set of generated files (hard-constraint #3).
 *
 * @since 0.1
 */
public final class OutputWriter {

    /**
     * Name of the per-output-tree manifest file. Records the relative paths this
     * tool emitted, so the next run can prune orphans. Committed alongside the
     * generated tree (L1) — a stale orphan removal is a reviewable diff (D3).
     */
    public static final String MANIFEST_NAME = ".exeris-codegen-manifest";

    private static final String MANIFEST_HEADER =
            "# Exeris Tooling generated-output manifest - DO NOT EDIT MANUALLY";

    private static final String GENERATED_HEADER = """
            /*
             * Generated by Exeris Tooling - DO NOT EDIT MANUALLY
             * Source: %s
             */
            """;

    private final Path outputDir;
    private final boolean addHeader;

    /** Relative paths (forward-slash) written during this run, in write order. */
    private final Set<String> writtenPaths = new LinkedHashSet<>();

    /**
     * Creates a new OutputWriter.
     *
     * @param outputDir Target directory for generated files
     */
    public OutputWriter(Path outputDir) {
        this(outputDir, true);
    }

    /**
     * Creates a new OutputWriter with header option.
     *
     * @param outputDir Target directory for generated files
     * @param addHeader Whether to add generation header to files
     */
    public OutputWriter(Path outputDir, boolean addHeader) {
        this.outputDir = Objects.requireNonNull(outputDir, "outputDir must not be null");
        this.addHeader = addHeader;
    }

    /**
     * Writes a Java source file.
     *
     * @param packageName Package name (e.g., "eu.exeris.domain.order"); empty for the default
     *                    package, whose sources are written at the output root
     * @param className   Simple class name (e.g., "OrderController")
     * @param source      Java source code
     * @param sourceInfo  Source entity info for header (e.g., "Order.java")
     * @throws IOException if writing fails, or, before anything is written, if a package segment is
     *                     empty, {@code .} or {@code ..} or holds a path separator, if the class name
     *                     holds a path separator, or if the target resolves outside the output
     *                     directory
     */
    public void writeJavaSource(String packageName, String className, String source, String sourceInfo)
            throws IOException {
        Objects.requireNonNull(className, "className must not be null");
        if (className.contains("/") || className.contains("\\")) {
            throw new IOException("Class name must not contain path separators: " + className);
        }
        Path packageDir = packageToPath(packageName);
        Path targetDir = outputDir.resolve(packageDir);
        Path targetFile = targetDir.resolve(className + ".java");
        Path contained = assertContained(targetFile);

        Files.createDirectories(contained.getParent());

        String content = addHeader
                ? GENERATED_HEADER.formatted(sourceInfo) + "\n" + source
                : source;

        Files.writeString(contained, content, StandardCharsets.UTF_8);
        track(contained);
    }

    /**
     * Writes a resource file (JSON, YAML, etc.).
     *
     * @param relativePath Relative path within output directory
     * @param content      File content
     * @throws IOException if writing fails, or, before anything is written, if the path resolves
     *                     outside the output directory
     */
    public void writeResource(String relativePath, String content) throws IOException {
        Objects.requireNonNull(relativePath, "relativePath must not be null");
        Path targetFile = outputDir.resolve(relativePath);
        Path contained = assertContained(targetFile);
        Files.createDirectories(contained.getParent());
        Files.writeString(contained, content, StandardCharsets.UTF_8);
        track(contained);
    }

    /**
     * Writes a binary resource file.
     *
     * @param relativePath Relative path within output directory
     * @param content      Binary content
     * @throws IOException if writing fails, or, before anything is written, if the path resolves
     *                     outside the output directory
     */
    public void writeResourceBytes(String relativePath, byte[] content) throws IOException {
        Objects.requireNonNull(relativePath, "relativePath must not be null");
        Path targetFile = outputDir.resolve(relativePath);
        Path contained = assertContained(targetFile);
        Files.createDirectories(contained.getParent());
        Files.write(contained, content);
        track(contained);
    }

    /**
     * Counts the files a {@link #pruneOrphansAndWriteManifest()} call would
     * delete right now — the previous-manifest paths this run did not re-emit —
     * <b>without</b> deleting anything. Backs the masked-compile-failure
     * guard: a run that would orphan files it generated nothing to replace is
     * almost always a build that failed before the annotation processor emitted
     * metadata, not an intentional teardown — wiping the committed tree on that
     * signal is the data-loss footgun the guard prevents.
     *
     * @return the number of orphans the next prune would remove
     * @throws IOException if reading the previous manifest fails
     * @since 0.6
     */
    public int countOrphans() throws IOException {
        Set<String> previous = readManifest();
        int orphans = 0;
        for (String rel : previous) {
            if (writtenPaths.contains(rel) || MANIFEST_NAME.equals(rel)) {
                continue;
            }
            orphans++;
        }
        return orphans;
    }

    /**
     * Records a file emitted by a <em>previous</em> run into <b>this</b> run's
     * manifest without rewriting it, so {@link #pruneOrphansAndWriteManifest()}
     * keeps it byte-untouched instead of deleting it as an orphan. Only a path
     * the previous run owns (listed in the prior manifest) that still exists on
     * disk is preserved — anything else is a no-op, so ownership is never
     * claimed over a user-authored file or a file that is already gone. Backs
     * the deferred capability validation: on a possibly-stale-metadata graph
     * failure the pipeline keeps the prior {@code cap-manifest.json} in place
     * rather than emitting from an unresolvable graph or letting the prune
     * remove it.
     *
     * @param relativePath forward-slash relative path within the output directory
     * @return {@code true} if the file was preserved (previously owned and present)
     * @throws IOException if reading the previous manifest fails
     * @since 0.6
     */
    public boolean preserve(String relativePath) throws IOException {
        Objects.requireNonNull(relativePath, "relativePath must not be null");
        String normalized = relativePath.replace('\\', '/');
        if (!readManifest().contains(normalized)) {
            return false;
        }
        Path root = outputDir.toAbsolutePath().normalize();
        Path file = outputDir.resolve(normalized).toAbsolutePath().normalize();
        // Defence in depth: never claim (or later prune) outside the output tree.
        if (!file.startsWith(root) || file.equals(root) || !Files.isRegularFile(file)) {
            return false;
        }
        writtenPaths.add(normalized);
        return true;
    }

    /**
     * Deletes files this tool emitted on a previous run that the current run did
     * not re-emit (orphans), prunes any directories left empty by that removal,
     * and writes the manifest of the current run's files.
     *
     * <p>Safe by construction: only paths listed in the previous manifest are
     * eligible for deletion, so user-authored files (never in the manifest) are
     * never removed. Call once, after all files for a run have been written.
     *
     * @return the number of orphaned files deleted
     * @throws IOException if reading the old manifest or writing the new one fails
     */
    public int pruneOrphansAndWriteManifest() throws IOException {
        Set<String> previous = readManifest();
        int pruned = 0;
        Set<Path> touchedDirs = new LinkedHashSet<>();
        Path root = outputDir.toAbsolutePath().normalize();

        for (String rel : previous) {
            if (writtenPaths.contains(rel) || MANIFEST_NAME.equals(rel)) {
                continue;
            }
            Path orphan = outputDir.resolve(rel).toAbsolutePath().normalize();
            // Defence in depth: never delete outside the output tree.
            if (!orphan.startsWith(root) || orphan.equals(root)) {
                continue;
            }
            if (Files.deleteIfExists(orphan)) {
                pruned++;
                touchedDirs.add(orphan.getParent());
            }
        }

        pruneEmptyDirs(touchedDirs);
        writeManifest();
        return pruned;
    }

    /**
     * Relative paths written during this run (forward-slash, sorted).
     * Package-private — test-visibility only; not part of the public API surface
     * before the 1.0.0 freeze.
     */
    Set<String> writtenPaths() {
        return new TreeSet<>(writtenPaths);
    }

    private void track(Path targetFile) {
        writtenPaths.add(relativize(targetFile));
    }

    private String relativize(Path targetFile) {
        Path root = outputDir.toAbsolutePath().normalize();
        return root.relativize(targetFile.toAbsolutePath().normalize()).toString().replace('\\', '/');
    }

    private Set<String> readManifest() throws IOException {
        Path manifest = outputDir.resolve(MANIFEST_NAME);
        if (!Files.exists(manifest)) {
            return Set.of();
        }
        Set<String> paths = new LinkedHashSet<>();
        for (String line : Files.readAllLines(manifest, StandardCharsets.UTF_8)) {
            String trimmed = line.strip();
            if (!trimmed.isEmpty() && !trimmed.startsWith("#")) {
                paths.add(trimmed);
            }
        }
        return paths;
    }

    private void writeManifest() throws IOException {
        List<String> lines = new ArrayList<>();
        lines.add(MANIFEST_HEADER);
        lines.addAll(new TreeSet<>(writtenPaths));
        Path root = outputDir.toAbsolutePath().normalize();
        Files.createDirectories(root);
        Files.writeString(root.resolve(MANIFEST_NAME),
                String.join("\n", lines) + "\n", StandardCharsets.UTF_8);
    }

    /** Deletes the given directories (and their now-empty parents) up to, but not including, the output dir. */
    private void pruneEmptyDirs(Set<Path> dirs) throws IOException {
        Path root = outputDir.toAbsolutePath().normalize();
        for (Path start : dirs) {
            Path dir = start != null ? start.toAbsolutePath().normalize() : null;
            while (dir != null && !dir.equals(root) && dir.startsWith(root) && isEmptyDir(dir)) {
                Files.deleteIfExists(dir);
                dir = dir.getParent();
            }
        }
    }

    private static boolean isEmptyDir(Path dir) throws IOException {
        if (!Files.isDirectory(dir)) {
            return false;
        }
        try (var entries = Files.list(dir)) {
            return entries.findAny().isEmpty();
        }
    }

    /**
     * Converts a package name to a file path after validating package segments; the default
     * package, an empty name, is the output root.
     *
     * @param packageName Java package name
     * @return Relative path
     * @throws IOException if a package segment is empty, invalid, or contains path separators
     */
    private Path packageToPath(String packageName) throws IOException {
        Objects.requireNonNull(packageName, "packageName must not be null");
        if (packageName.isEmpty()) {
            return Path.of("");
        }
        validatePackage(packageName);
        return Path.of(packageName.replace('.', '/'));
    }

    private static void validatePackage(String packageName) throws IOException {
        Objects.requireNonNull(packageName, "packageName must not be null");
        if (packageName.contains("/") || packageName.contains("\\")) {
            throw new IOException("Package name must not contain path separators: " + packageName);
        }
        String[] segments = packageName.split("\\.", -1);
        for (String segment : segments) {
            if (segment.isEmpty() || ".".equals(segment) || "..".equals(segment)) {
                throw new IOException("Invalid package segment '" + segment + "' in package: " + packageName);
            }
        }
    }

    private Path assertContained(Path target) throws IOException {
        Path root = outputDir.toAbsolutePath().normalize();
        Path normalized = target.toAbsolutePath().normalize();
        if (!normalized.startsWith(root) || normalized.equals(root)) {
            throw new IOException("Target path escapes output directory: " + target);
        }
        return normalized;
    }

    /**
     * Returns the root directory generated files are written under.
     *
     * @return the output root
     */
    public Path getOutputDir() {
        return outputDir;
    }

    /**
     * Reports whether the writer prepends the generated-file header to the Java sources it writes.
     *
     * @return {@code true} when the header is added
     */
    public boolean isAddHeader() {
        return addHeader;
    }
}
