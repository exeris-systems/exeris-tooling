package eu.exeris.tooling.codegen.java.kernel;

import com.palantir.javapoet.ClassName;
import com.palantir.javapoet.FieldSpec;
import com.palantir.javapoet.MethodSpec;
import com.palantir.javapoet.ParameterizedTypeName;
import com.palantir.javapoet.TypeName;
import com.palantir.javapoet.TypeSpec;
import eu.exeris.tooling.codegen.core.generator.KernelArtifactGenerator;
import eu.exeris.tooling.codegen.core.generator.KernelArtifactGenerator.ArtifactType;
import eu.exeris.tooling.codegen.core.generator.GeneratedFile;
import eu.exeris.tooling.codegen.java.support.DomainPackages;
import eu.exeris.tooling.codegen.java.support.KernelScaffold;
import eu.exeris.sdk.sourcemodel.ast.DomainMetadata;

import javax.lang.model.element.Modifier;
import java.util.List;

/**
 * Kernel Service Generator.
 *
 * <p>Generates a CRUD service class delegating to the corresponding
 * {@code *Repository}. Pure POJO — no direct Kernel API surface. Domain-event
 * publishing is not the service's: the generated handler publishes, because
 * it alone knows which action a write came from (ADR-075).
 *
 * <p>The service is the one seam every generated write passes through — the
 * handler's create, update and delete, each action, and each streaming action.
 * For an entity {@link KernelGraphSyncGenerator#syncedByService} admits, it
 * therefore takes the entity's {@code *GraphSync} and projects every write
 * into the graph after the repository returns: {@code syncToGraph} on the
 * entity the repository returned, which is the row as stored, and
 * {@code deleteFromGraph} after a hard or a soft delete, since a soft-deleted
 * row is hidden from every read. A write the repository refuses throws before
 * the graph is touched. A graph failure propagates (ADR-070 Amendment 4); a
 * consumer who wants the write to stand regardless installs a graph sync
 * whose methods catch, through {@code RuntimeComponents}.
 *
 * @implNote Emission is JavaPoet-based (ADR-015).
 *
 * @since 0.1
 */
public class KernelServiceGenerator implements KernelArtifactGenerator {

    private static final ClassName UUID = ClassName.get("java.util", "UUID");
    private static final ClassName OPTIONAL = ClassName.get("java.util", "Optional");
    private static final ClassName LIST = ClassName.get("java.util", "List");
    /** The graph-sync field and constructor parameter of a synced entity's service. */
    private static final String GRAPH_SYNC = "graphSync";
    private static final String UPDATED = "updated";

    /**
     * Creates the generator. It keeps no per-domain state, so one instance serves every domain
     * in a build.
     */
    public KernelServiceGenerator() {
        // no state to initialise
    }

    @Override
    public GeneratedFile generate(DomainMetadata metadata) {
        String packageName = DomainPackages.sibling(metadata, DomainPackages.SERVICE);
        String entity = metadata.entityName();
        String className = entity + "Service";
        String repoName = entity + "Repository";

        ClassName entityType = ClassName.get(metadata.packageName(), entity);
        ClassName repoType = ClassName.get(
                DomainPackages.sibling(metadata, DomainPackages.REPOSITORY), repoName);
        TypeName optionalOfEntity = ParameterizedTypeName.get(OPTIONAL, entityType);
        TypeName listOfEntity = ParameterizedTypeName.get(LIST, entityType);

        boolean synced = KernelGraphSyncGenerator.syncedByService(metadata);
        ClassName graphSyncType = synced ? KernelGraphSyncGenerator.graphSyncType(metadata) : null;

        TypeSpec.Builder builder = KernelScaffold.publicClass(className)
                .addJavadoc("Service for $L domain operations.\n", entity);
        addGraphJavadoc(builder, metadata, synced);
        builder.addJavadoc("<p>Generated by Exeris Codegen. DO NOT EDIT.\n")
                .addField(FieldSpec.builder(repoType, "repository",
                        Modifier.PRIVATE, Modifier.FINAL).build());
        if (synced) {
            builder.addField(FieldSpec.builder(graphSyncType, GRAPH_SYNC,
                    Modifier.PRIVATE, Modifier.FINAL).build());
        }

        builder.addMethod(buildConstructor(repoType, graphSyncType))
                .addMethod(buildFindById(optionalOfEntity))
                .addMethod(buildFindAll(listOfEntity))
                .addMethod(buildFindPage(metadata));

        // T8: delegating finders mirroring the repository surface (parity), in
        // the same stable sorted order — filterable fields by name, then
        // MANY_TO_ONE FK finders by relationship name.
        for (MethodSpec finder : buildFinders(metadata, listOfEntity)) {
            builder.addMethod(finder);
        }

        builder.addMethod(buildSave(entityType, synced))
                .addMethod(buildUpdate(entityType, synced));
        if (KernelRepositoryGenerator.hasRequestUpdate(metadata)) {
            builder.addMethod(buildUpdateFromRequest(entityType, synced));
        }
        builder.addMethod(buildDelete(synced))
                .addMethod(buildCount());

        return new GeneratedFile(packageName, className,
                KernelScaffold.render(packageName, builder.build()), ArtifactType.SERVICE);
    }

    /**
     * States the graph projection in the class Javadoc of a graph entity's service: what the
     * service calls, or, for a tenant-partitioned entity, why it calls nothing. A non-graph
     * service carries no graph sentence.
     */
    private static void addGraphJavadoc(TypeSpec.Builder builder, DomainMetadata metadata, boolean synced) {
        if (synced) {
            builder.addJavadoc("<p>Every write is projected into the graph after the repository returns:\n")
                    .addJavadoc("{@code syncToGraph} on the entity as stored, {@code deleteFromGraph} after\n")
                    .addJavadoc("a delete. The two stores share no transaction, so a graph failure\n")
                    .addJavadoc("propagates after the row has committed.\n");
        } else if (metadata.hasGraphMetadata()) {
            builder.addJavadoc("<p>Writes are not projected into the graph: the entity is tenant-partitioned,\n")
                    .addJavadoc("and the Community graph engine cannot scope a traversal to the acting tenant\n")
                    .addJavadoc("on a request thread, where no persistence engine is bound, and keeps its nodes\n")
                    .addJavadoc("in one table that carries no tenant. {@code RuntimeComponents} still builds\n")
                    .addJavadoc("the entity's graph sync for code that calls it.\n");
        }
    }

    /**
     * T8: delegating finders for filterable fields and MANY_TO_ONE FK columns.
     * Resolved from {@link KernelRepositoryGenerator#finderSpecs} — the same set, in the same
     * byte-deterministic order, as the repository declares. A service finder with no repository
     * method behind it would not compile, so the two surfaces are emitted from one source rather
     * than kept in step by hand.
     */
    private List<MethodSpec> buildFinders(DomainMetadata metadata, TypeName listOfEntity) {
        return KernelRepositoryGenerator.finderSpecs(metadata).stream()
                .map(spec -> buildDelegatingFinder(listOfEntity, spec))
                .toList();
    }

    private MethodSpec buildDelegatingFinder(TypeName listOfEntity,
                                             KernelRepositoryGenerator.FinderSpec spec) {
        return MethodSpec.methodBuilder(spec.methodName())
                .addModifiers(Modifier.PUBLIC)
                .returns(listOfEntity)
                .addParameter(spec.paramType(), spec.paramName())
                .addStatement("return repository.$L($L)", spec.methodName(), spec.paramName())
                .build();
    }

    private MethodSpec buildConstructor(ClassName repoType, ClassName graphSyncType) {
        MethodSpec.Builder constructor = MethodSpec.constructorBuilder()
                .addModifiers(Modifier.PUBLIC)
                .addParameter(repoType, "repository")
                .addStatement("this.repository = repository");
        if (graphSyncType != null) {
            constructor.addParameter(graphSyncType, GRAPH_SYNC)
                    .addStatement("this.$L = $L", GRAPH_SYNC, GRAPH_SYNC);
        }
        return constructor.build();
    }

    /** {@code graphSync.syncToGraph(<local>);} after a write, for a synced entity. */
    private static void syncWritten(MethodSpec.Builder method, boolean synced, String local) {
        if (synced) {
            method.addStatement("$L.syncToGraph($L)", GRAPH_SYNC, local);
        }
    }

    private MethodSpec buildFindById(TypeName optionalOfEntity) {
        return MethodSpec.methodBuilder("findById")
                .addModifiers(Modifier.PUBLIC)
                .returns(optionalOfEntity)
                .addParameter(UUID, "id")
                .addStatement("return repository.findById(id)")
                .build();
    }

    private MethodSpec buildFindAll(TypeName listOfEntity) {
        return MethodSpec.methodBuilder("findAll")
                .addModifiers(Modifier.PUBLIC)
                .returns(listOfEntity)
                .addStatement("return repository.findAll()")
                .build();
    }

    /**
     * The list route's read: one page of the rows the query's filters select. Every row, unpaged,
     * stays available as {@code findAll()} for the consumer's own code; the generated handler reads
     * through this method only.
     */
    private MethodSpec buildFindPage(DomainMetadata metadata) {
        return MethodSpec.methodBuilder("findPage")
                .addModifiers(Modifier.PUBLIC)
                .returns(KernelListQueryGenerator.pageType(metadata))
                .addParameter(KernelListQueryGenerator.listQueryType(metadata), "query")
                .addStatement("return repository.findPage(query)")
                .build();
    }

    private MethodSpec buildSave(ClassName entityType, boolean synced) {
        MethodSpec.Builder method = MethodSpec.methodBuilder("save")
                .addModifiers(Modifier.PUBLIC)
                .returns(entityType)
                .addParameter(entityType, "entity")
                .addStatement("$T saved = repository.save(entity)", entityType);
        syncWritten(method, synced, "saved");
        return method.addStatement("return saved").build();
    }

    private MethodSpec buildUpdate(ClassName entityType, boolean synced) {
        MethodSpec.Builder method = MethodSpec.methodBuilder("update")
                .addModifiers(Modifier.PUBLIC)
                .returns(entityType)
                .addParameter(UUID, "id")
                .addParameter(entityType, "entity")
                .addStatement("$T updated = repository.update(id, entity)", entityType);
        syncWritten(method, synced, UPDATED);
        return method.addStatement("return updated").build();
    }

    /**
     * The update a request body drives, emitted beside {@code update} when the entity has read-only
     * fields: it keeps their stored value, where {@code update}, which an action's entity method
     * drives, writes them.
     */
    private MethodSpec buildUpdateFromRequest(ClassName entityType, boolean synced) {
        String name = KernelRepositoryGenerator.UPDATE_FROM_REQUEST_METHOD;
        MethodSpec.Builder method = MethodSpec.methodBuilder(name)
                .addModifiers(Modifier.PUBLIC)
                .returns(entityType)
                .addParameter(UUID, "id")
                .addParameter(entityType, "entity")
                .addJavadoc("Updates from a request body: the read-only fields keep their stored value.\n")
                .addStatement("$T updated = repository.$L(id, entity)", entityType, name);
        syncWritten(method, synced, UPDATED);
        return method.addStatement("return updated").build();
    }

    private MethodSpec buildDelete(boolean synced) {
        MethodSpec.Builder method = MethodSpec.methodBuilder("delete")
                .addModifiers(Modifier.PUBLIC)
                .returns(TypeName.VOID)
                .addParameter(UUID, "id")
                .addStatement("repository.deleteById(id)");
        if (synced) {
            method.addStatement("$L.deleteFromGraph(id)", GRAPH_SYNC);
        }
        return method.build();
    }

    private MethodSpec buildCount() {
        return MethodSpec.methodBuilder("count")
                .addModifiers(Modifier.PUBLIC)
                .returns(TypeName.LONG)
                .addStatement("return repository.count()")
                .build();
    }

    @Override
    public ArtifactType artifactType() {
        return ArtifactType.SERVICE;
    }
}
