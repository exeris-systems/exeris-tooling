/**
 * The emitted file header: one helper writes it, and no other source under `src/` spells out its
 * provenance line or its do-not-edit notice.
 *
 * `test/output/header-version-free.spec.ts` checks what the headers say in emitted output; this
 * spec checks where they are written, so a new emitter cannot carry header text of its own.
 */

import { readdirSync, readFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import {
  carriesGeneratorMarker,
  fileHeader,
  fileHeaderLines,
  GENERATOR_MARKER_LINES,
  lineHeaderLines,
} from '../../src/generators/file-header.js';
import { buildGeneratedFiles } from '../../src/orchestrator.js';
import { DEFAULT_CONFIG } from '../../src/config.js';
import { DomainMetadataSchema, ViewMetadataSchema } from '../../src/models/domain-model.js';

const PROVENANCE = 'Generated by @exeris/codegen-ts';
const DO_NOT_EDIT = 'DO NOT EDIT - This file is auto-generated';
const SRC = join(dirname(fileURLToPath(import.meta.url)), '../../src');
const HELPER = 'generators/file-header.ts';

describe('fileHeaderLines', () => {
  it('writes the title, the provenance line and the do-not-edit notice by default', () => {
    expect(fileHeaderLines({ title: 'Order API Service' })).toEqual([
      '/**',
      ' * Order API Service',
      ` * ${PROVENANCE}`,
      ' * DO NOT EDIT - This file is auto-generated',
      ' */',
    ]);
  });

  it('omits the do-not-edit notice on request', () => {
    expect(fileHeaderLines({ title: 'Services - Barrel Export', doNotEdit: 'omit' })).toEqual([
      '/**',
      ' * Services - Barrel Export',
      ` * ${PROVENANCE}`,
      ' */',
    ]);
  });

  it('names the ADR on the provenance line and writes notes after the notice', () => {
    expect(
      fileHeaderLines({ title: 'Order SSE Live-View Stream Client', adr: 'ADR-043 Slice 1', notes: ['', 'Parity twin.'] }),
    ).toEqual([
      '/**',
      ' * Order SSE Live-View Stream Client',
      ` * ${PROVENANCE} (ADR-043 Slice 1)`,
      ' * DO NOT EDIT - This file is auto-generated',
      ' *',
      ' * Parity twin.',
      ' */',
    ]);
  });

  it('places the notice after the notes, or on the provenance line', () => {
    expect(fileHeaderLines({ title: 'Order List Component', notes: ['Pages on the server.'], doNotEdit: 'last' })).toEqual([
      '/**',
      ' * Order List Component',
      ` * ${PROVENANCE}`,
      ' * Pages on the server.',
      ' * DO NOT EDIT - This file is auto-generated',
      ' */',
    ]);
    expect(fileHeaderLines({ title: 'Home Page Component', doNotEdit: 'on-provenance' })).toEqual([
      '/**',
      ' * Home Page Component',
      ` * ${PROVENANCE} — DO NOT EDIT.`,
      ' */',
    ]);
  });

  it('writes lead lines before the provenance line, with bare or spaced empty lines', () => {
    const lead = ['', 'Signal-based state management.', ''];
    expect(fileHeaderLines({ title: 'Order Signal Store', lead })).toEqual([
      '/**',
      ' * Order Signal Store',
      ' *',
      ' * Signal-based state management.',
      ' *',
      ` * ${PROVENANCE}`,
      ' * DO NOT EDIT - This file is auto-generated',
      ' */',
    ]);
    expect(fileHeaderLines({ title: 'Order Signal Store', lead, blank: 'spaced' })).toEqual([
      '/**',
      ' * Order Signal Store',
      ' * ',
      ' * Signal-based state management.',
      ' * ',
      ` * ${PROVENANCE}`,
      ' * DO NOT EDIT - This file is auto-generated',
      ' */',
    ]);
  });

  it('fileHeader joins the same lines with no trailing newline', () => {
    const header = { title: 'Application Routes', doNotEdit: 'omit' } as const;
    expect(fileHeader(header)).toBe(fileHeaderLines(header).join('\n'));
  });
});

describe('lineHeaderLines', () => {
  it('writes the title and the do-not-edit notice as line comments', () => {
    expect(lineHeaderLines('Generated barrel export')).toEqual([
      '// Generated barrel export',
      `// ${DO_NOT_EDIT}`,
    ]);
  });
});

describe('carriesGeneratorMarker', () => {
  it.each([
    ['the default block header', fileHeader({ title: 'T' })],
    ['a block header without the notice', fileHeader({ title: 'T', doNotEdit: 'omit' })],
    ['a block header with the notice on the provenance line', fileHeader({ title: 'T', doNotEdit: 'on-provenance' })],
    ['a line-comment header', lineHeaderLines('Generated barrel export').join('\n')],
  ])('recognises %s', (_label, header) => {
    expect(carriesGeneratorMarker(`${header}\n\nexport const x = 1;\n`)).toBe(true);
  });

  it('does not recognise a file without a header', () => {
    expect(carriesGeneratorMarker("import { Component } from '@angular/core';\n")).toBe(false);
  });

  it(`reads only the first ${GENERATOR_MARKER_LINES} lines`, () => {
    const late = `${'\n'.repeat(GENERATOR_MARKER_LINES)}${fileHeader({ title: 'T' })}\n`;
    expect(carriesGeneratorMarker(late)).toBe(false);
  });

  // The proof of a 0.9.x manifest entry rests on this: every emitted file a regeneration may
  // rewrite starts with a generator header.
  it('holds for every non-seed text file the pipeline emits', () => {
    const domain = DomainMetadataSchema.parse({
      packageName: 'com.shop',
      entityName: 'Order',
      fields: [{ name: 'id', type: 'java.util.UUID' }, { name: 'status', type: 'com.shop.Status', enumType: 'com.shop.Status' }],
      events: [{ name: 'OrderPlaced', payloadFields: ['id'] }],
      sagaMetadata: { name: 'OrderFulfilment', steps: [{ name: 'reserveStock' }] },
      realTimeApi: true,
      actions: [{ name: 'track', streaming: true }],
    });
    const enums = [{ name: 'Status', qualifiedName: 'com.shop.Status', packageName: 'com.shop', values: [] }];
    const views = [ViewMetadataSchema.parse({ name: 'Board', regions: [] })];
    for (const config of [
      { ...DEFAULT_CONFIG, generateTests: true },
      { ...DEFAULT_CONFIG, scaffold: false },
    ]) {
      const unmarked = buildGeneratedFiles([domain], enums, config, views)
        .filter((f) => f.overwritable !== false && !f.path.endsWith('favicon.ico'))
        .filter((f) => !carriesGeneratorMarker(f.content))
        .map((f) => f.path);
      expect(unmarked).toEqual([]);
    }
  });
});

describe('the provenance line and the do-not-edit notice are written only by the helper', () => {
  const sources = (readdirSync(SRC, { recursive: true }) as string[])
    .filter((p) => p.endsWith('.ts'))
    .map((p) => relative(SRC, join(SRC, p)).split(sep).join('/'));

  it('scans the generator sources', () => {
    expect(sources).toContain(HELPER);
    expect(sources.filter((p) => p.startsWith('generators/') && p.endsWith('-gen.ts')).length).toBeGreaterThan(15);
  });

  it('no source under src/ outside the helper contains the provenance text', () => {
    const offenders = sources.filter((p) => p !== HELPER && readFileSync(join(SRC, p), 'utf8').includes(PROVENANCE));
    expect(offenders).toEqual([]);
  });

  it('the helper contains the provenance text once', () => {
    expect(readFileSync(join(SRC, HELPER), 'utf8').split(PROVENANCE).length - 1).toBe(1);
  });

  it('no source under src/ outside the helper contains the do-not-edit notice', () => {
    const offenders = sources.filter((p) => p !== HELPER && readFileSync(join(SRC, p), 'utf8').includes(DO_NOT_EDIT));
    expect(offenders).toEqual([]);
  });

  it('the helper contains the do-not-edit notice once', () => {
    expect(readFileSync(join(SRC, HELPER), 'utf8').split(DO_NOT_EDIT).length - 1).toBe(1);
  });
});
