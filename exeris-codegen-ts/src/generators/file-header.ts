/**
 * The leading comment of every file the generators emit.
 *
 * The provenance line and the do-not-edit notice are written here and nowhere else, so what an
 * emitted file says about its origin is decided in one place. ADR-092 requires the provenance line
 * to carry no per-release value: a release that changes no emitter regenerates byte-identical
 * output. A spec scans `src/` and fails on either text appearing outside this module.
 */

const PROVENANCE = 'Generated by @exeris/codegen-ts';
const DO_NOT_EDIT = 'DO NOT EDIT - This file is auto-generated';
const DO_NOT_EDIT_INLINE = '— DO NOT EDIT.';

/** Where the do-not-edit notice is written, if at all. */
export type DoNotEditPlacement =
  /** Its own line, directly after the provenance line. */
  | 'after-provenance'
  /** Appended to the provenance line. */
  | 'on-provenance'
  /** Its own line, after `notes`. */
  | 'last'
  /** Not written. */
  | 'omit';

export interface FileHeader {
  /** The first line of the block: what the file is. */
  title: string;
  /** Lines between the title and the provenance line. */
  lead?: readonly string[];
  /** The ADR the file implements, named in parentheses on the provenance line. */
  adr?: string;
  /** Lines after the provenance line and, when it follows it, the do-not-edit notice. */
  notes?: readonly string[];
  /** Defaults to `'after-provenance'`. */
  doNotEdit?: DoNotEditPlacement;
  /**
   * How an empty `lead` or `notes` line is written: `' *'` (`'bare'`, the default) or `' * '`
   * (`'spaced'`).
   */
  blank?: 'bare' | 'spaced';
}

/** The header as lines, from the opening `/**` to the closing ` *\/`, with no line after it. */
export function fileHeaderLines(header: FileHeader): string[] {
  const placement = header.doNotEdit ?? 'after-provenance';
  const emptyLine = header.blank === 'spaced' ? ' * ' : ' *';
  const line = (text: string): string => (text === '' ? emptyLine : ` * ${text}`);

  let provenance = header.adr ? `${PROVENANCE} (${header.adr})` : PROVENANCE;
  if (placement === 'on-provenance') provenance += ` ${DO_NOT_EDIT_INLINE}`;

  const lines = ['/**', line(header.title)];
  for (const text of header.lead ?? []) lines.push(line(text));
  lines.push(line(provenance));
  if (placement === 'after-provenance') lines.push(line(DO_NOT_EDIT));
  for (const text of header.notes ?? []) lines.push(line(text));
  if (placement === 'last') lines.push(line(DO_NOT_EDIT));
  lines.push(' */');
  return lines;
}

/** The header as text, ending at the closing ` *\/` with no newline after it. */
export function fileHeader(header: FileHeader): string {
  return fileHeaderLines(header).join('\n');
}

/**
 * A header of `//` line comments, for a file whose header is not a block: the title, then the
 * do-not-edit notice. It carries no provenance line.
 */
export function lineHeaderLines(title: string): string[] {
  return [`// ${title}`, `// ${DO_NOT_EDIT}`];
}

/** How many leading lines {@link carriesGeneratorMarker} reads. Every header ends within it. */
export const GENERATOR_MARKER_LINES = 10;

/**
 * Whether `content` starts with a header this package writes: its first
 * {@link GENERATOR_MARKER_LINES} lines carry the provenance line or the do-not-edit notice. Every
 * emitted file except the scaffold's seed files and `favicon.ico` has one, in 0.9.x as in this
 * release, so the writer accepts it as proof that a file a 0.9.x manifest lists is generated output
 * rather than a hand-written file 0.9.x skipped.
 */
export function carriesGeneratorMarker(content: string): boolean {
  const head = content.split('\n', GENERATOR_MARKER_LINES).join('\n');
  return head.includes(PROVENANCE) || head.includes(DO_NOT_EDIT);
}
