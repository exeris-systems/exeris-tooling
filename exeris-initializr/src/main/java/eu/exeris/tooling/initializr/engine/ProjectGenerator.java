package eu.exeris.tooling.initializr.engine;

import eu.exeris.tooling.initializr.model.DatabaseType;
import eu.exeris.tooling.initializr.model.ProjectScaffoldRequest;
import eu.exeris.tooling.initializr.model.ProjectTopology;
import eu.exeris.tooling.initializr.model.ProjectTree;
import eu.exeris.tooling.initializr.model.ScaffoldFile;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;

/**
 * Builds the file tree of a new project from a {@link ProjectScaffoldRequest}.
 *
 * <p>A backend is a Maven project on {@code eu.exeris:exeris-app-parent} with a dependency on
 * {@code eu.exeris:exeris-app-starter}, and declares nothing else but what the starter leaves to the
 * application: a JDBC driver, and JUnit 5 and AssertJ for the generated tests. Its source is one
 * {@code @ExerisDomain} entity; everything else is generated by its own build. A frontend is an npm
 * project that runs {@code @exeris/codegen-ts}; the Angular application is that generator's output,
 * written into {@code app/} beside it, so no file here has a path the generator also writes.
 *
 * <p>The tree is a function of the request and the versions: the same input gives the same paths,
 * order and bytes.
 *
 * @since 0.10
 */
public final class ProjectGenerator {

    private static final String TEMPLATES = "/eu/exeris/tooling/initializr/templates/";
    private static final String BACKEND = "backend/";
    private static final String FRONTEND = "frontend/";

    /** The port a backend-only project is run on: the kernel's default HTTP port. */
    private static final int BACKEND_PORT = 8080;
    /** The port the backend of an E2E project is run on: where the generated Angular proxy forwards. */
    private static final int E2E_BACKEND_PORT = 8443;

    private ProjectGenerator() {
    }

    /**
     * Builds the files of the project a request describes.
     *
     * @param request  the project
     * @param versions the versions the project names
     * @return the project's files, in the order they are written
     * @since 0.10
     */
    public static ProjectTree generate(ProjectScaffoldRequest request, ScaffoldVersions versions) {
        Objects.requireNonNull(request, "request");
        Objects.requireNonNull(versions, "versions");
        Map<String, Object> context = context(request, versions);
        List<ScaffoldFile> files = new ArrayList<>();

        files.add(ScaffoldFile.text(".gitignore", template("gitignore", context)));
        switch (request.topology()) {
            case BACKEND_ONLY -> {
                files.add(ScaffoldFile.text(".gitattributes", template("gitattributes/backend-only", context)));
                files.add(ScaffoldFile.text("README.md", template("readme/backend-only.md", context)));
                backend(request, "", context, files);
            }
            case E2E -> {
                files.add(ScaffoldFile.text(".gitattributes", template("gitattributes/e2e", context)));
                files.add(ScaffoldFile.text("README.md", template("readme/e2e.md", context)));
                backend(request, BACKEND, context, files);
                files.add(ScaffoldFile.text(FRONTEND + "package.json", template("frontend/package.json", context)));
            }
        }
        if (request.database() == DatabaseType.POSTGRESQL) {
            files.add(ScaffoldFile.text("docker-compose.yml", template("docker-compose.yml", context)));
        }
        return new ProjectTree(files);
    }

    private static void backend(ProjectScaffoldRequest request, String root, Map<String, Object> context,
                                List<ScaffoldFile> files) {
        String domain = "src/main/java/" + request.packageName().replace('.', '/') + "/domain/";
        files.add(ScaffoldFile.text(root + "pom.xml", template("backend/pom.xml", context)));
        files.add(ScaffoldFile.script(root + "first-build.sh", template("backend/first-build.sh", context)));
        files.add(ScaffoldFile.text(root + domain + request.entityName() + ".java",
                template("backend/Entity.java", context)));
    }

    private static Map<String, Object> context(ProjectScaffoldRequest request, ScaffoldVersions versions) {
        DatabaseType database = request.database();
        String databaseName = Names.databaseName(request.artifactId());
        boolean e2e = request.topology() == ProjectTopology.E2E;

        Map<String, Object> context = new HashMap<>();
        context.put("name", request.name());
        context.put("nameXml", Names.xml(request.name()));
        context.put("groupId", request.groupId());
        context.put("artifactId", request.artifactId());
        context.put("packageName", request.packageName());
        context.put("entityName", request.entityName());
        context.put("entityModule", Names.plural(Names.kebab(request.entityName())));
        context.put("npmName", Names.npmName(request.artifactId()));
        context.put("toolingVersion", versions.tooling());
        context.put("junitVersion", versions.junit());
        context.put("assertjVersion", versions.assertj());
        context.put("driverGroupId", database.driverGroupId());
        context.put("driverArtifactId", database.driverArtifactId());
        context.put("driverVersion", database == DatabaseType.H2 ? versions.h2() : versions.postgresql());
        context.put("databaseLabel", database == DatabaseType.H2 ? "H2" : "PostgreSQL");
        context.put("databaseName", databaseName);
        context.put("jdbcUrl", database.jdbcUrl(databaseName));
        context.put("httpPort", e2e ? E2E_BACKEND_PORT : BACKEND_PORT);
        context.put("postgresql", database == DatabaseType.POSTGRESQL);
        context.put("e2e", e2e);
        context.put("backendDir", e2e ? BACKEND : "");

        context.put("buildSection", template("readme/build.md", context));
        context.put("runSection", template("readme/run.md", context));
        context.put("npmSection", template("readme/npm.md", context));
        return context;
    }

    private static String template(String name, Map<String, Object> context) {
        return TemplateRenderer.render(TemplateRenderer.readResource(TEMPLATES + name + ".tmpl"), context);
    }
}
