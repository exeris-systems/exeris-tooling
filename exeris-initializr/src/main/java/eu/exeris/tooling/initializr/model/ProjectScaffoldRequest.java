package eu.exeris.tooling.initializr.model;

import java.util.ArrayList;
import java.util.List;
import java.util.Objects;

/**
 * Specification request for scaffolding an Exeris project.
 */
public record ProjectScaffoldRequest(
        String name,
        String slug,
        String groupId,
        String artifactId,
        String packageName,
        String version,
        String description,
        ProjectTopology topology,
        DatabaseType database,
        List<ExerisCapability> capabilities,
        boolean includeDemoEntity,
        String entityName,
        String entityPath,
        String entityModule
) {
    public ProjectScaffoldRequest {
        Objects.requireNonNull(name, "name must not be null");
        Objects.requireNonNull(slug, "slug must not be null");
        Objects.requireNonNull(groupId, "groupId must not be null");
        Objects.requireNonNull(artifactId, "artifactId must not be null");
        Objects.requireNonNull(packageName, "packageName must not be null");
        Objects.requireNonNull(topology, "topology must not be null");
        Objects.requireNonNull(database, "database must not be null");
        if (version == null || version.isBlank()) {
            version = "0.1.0-SNAPSHOT";
        }
        if (description == null) {
            description = "Exeris project scaffolded via Initializr";
        }
        if (capabilities == null) {
            capabilities = List.of();
        } else {
            capabilities = List.copyOf(capabilities);
        }
        if (entityName == null || entityName.isBlank()) {
            entityName = "Item";
        }
        if (entityPath == null || entityPath.isBlank()) {
            entityPath = "/items";
        }
        if (entityModule == null || entityModule.isBlank()) {
            entityModule = "inventory";
        }
    }

    public static Builder builder() {
        return new Builder();
    }

    public static final class Builder {
        private String name = "my-exeris-app";
        private String slug = "my-exeris-app";
        private String groupId = "eu.exeris.sample";
        private String artifactId = "my-exeris-app";
        private String packageName = "eu.exeris.sample.app";
        private String version = "0.1.0-SNAPSHOT";
        private String description = "Exeris application generated by Initializr";
        private ProjectTopology topology = ProjectTopology.E2E;
        private DatabaseType database = DatabaseType.H2;
        private List<ExerisCapability> capabilities = new ArrayList<>();
        private boolean includeDemoEntity = true;
        private String entityName = "Item";
        private String entityPath = "/items";
        private String entityModule = "inventory";

        public Builder name(String name) {
            this.name = name;
            return this;
        }

        public Builder slug(String slug) {
            this.slug = slug;
            return this;
        }

        public Builder groupId(String groupId) {
            this.groupId = groupId;
            return this;
        }

        public Builder artifactId(String artifactId) {
            this.artifactId = artifactId;
            return this;
        }

        public Builder packageName(String packageName) {
            this.packageName = packageName;
            return this;
        }

        public Builder version(String version) {
            this.version = version;
            return this;
        }

        public Builder description(String description) {
            this.description = description;
            return this;
        }

        public Builder topology(ProjectTopology topology) {
            this.topology = topology;
            return this;
        }

        public Builder database(DatabaseType database) {
            this.database = database;
            return this;
        }

        public Builder capabilities(List<ExerisCapability> capabilities) {
            this.capabilities = capabilities != null ? new ArrayList<>(capabilities) : new ArrayList<>();
            return this;
        }

        public Builder addCapability(ExerisCapability capability) {
            if (capability != null && !this.capabilities.contains(capability)) {
                this.capabilities.add(capability);
            }
            return this;
        }

        public Builder includeDemoEntity(boolean includeDemoEntity) {
            this.includeDemoEntity = includeDemoEntity;
            return this;
        }

        public Builder entityName(String entityName) {
            this.entityName = entityName;
            return this;
        }

        public Builder entityPath(String entityPath) {
            this.entityPath = entityPath;
            return this;
        }

        public Builder entityModule(String entityModule) {
            this.entityModule = entityModule;
            return this;
        }

        public ProjectScaffoldRequest build() {
            return new ProjectScaffoldRequest(
                    name, slug, groupId, artifactId, packageName, version, description,
                    topology, database, capabilities, includeDemoEntity, entityName, entityPath, entityModule
            );
        }
    }
}
